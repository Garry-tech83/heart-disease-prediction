import {
  AlertTriangle,
  CheckCircle2,
  RotateCcw,
} from "lucide-react";

function PredictionResult({ result, onReset }) {
  const isElevated = result.prediction === 1;

  return (
    <section className="result-section">

      <div className="result-card">

        <div
          className={`result-icon ${
            isElevated ? "result-danger" : "result-safe"
          }`}
        >
          {isElevated ? (
            <AlertTriangle size={30} />
          ) : (
            <CheckCircle2 size={30} />
          )}
        </div>

        <p className="result-label">
          MODEL-ESTIMATED RESULT
        </p>

        <h2>
          {isElevated
            ? "Elevated Risk"
            : "Lower Estimated Risk"}
        </h2>

        <p className="result-description">
          {result.result}
        </p>

        <div className="result-probability">
          <span>{result.probability}%</span>
          <small>Model score</small>
        </div>

        <div className="result-warning">
          <AlertTriangle size={17} />

          <p>
            This result is generated by a machine-learning
            prototype and is not a medical diagnosis.
          </p>
        </div>

        <button
          className="reset-button"
          onClick={onReset}
        >
          <RotateCcw size={17} />
          Analyze Again
        </button>

      </div>

    </section>
  );
}

export default PredictionResult;